    private void btnOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOkActionPerformed
        try {
        // Criar objeto fornecedor
        Fornecedor fornecedor = new Fornecedor();

        fornecedor.setCnpj(txtCNPJ.getText());
        fornecedor.setNome(txtNome.getText());
        fornecedor.setEmail(txtEmail.getText());
        fornecedor.setTelefone(txtTelefone.getText());
        fornecedor.setEndereco(txtEndereco.getText());
        fornecedor.setCep(txtCEP.getText());

        FornecedorDAO dao = new FornecedorDAO();

        // Diferencia entre novo fornecedor ou existente
        if (Id ==null) {
            // NOVO FORNECEDOR
            dao.cadastrarFornecedor(fornecedor);
            JOptionPane.showMessageDialog(this, "Fornecedor cadastrado com sucesso!");
            // Limpar campos após salvar
            txtCNPJ.setText(""); 
            txtNome.setText("");
            txtEmail.setText("");
            txtCEP.setText("");
            txtEndereco.setText("");
            txtTelefone.setText("");
        } else {
            // EDITANDO EXISTENTE
            fornecedor.setId_fornecedor(Id);
            dao.atualizarFornecedor(fornecedor);
            JOptionPane.showMessageDialog(this, "Fornecedor atualizado com sucesso!");
        }

            // Limpar campos após salvar
            txtCNPJ.setText(""); //seta as caixas de texto para vazio assim que insere um cliente
            txtNome.setText("");
            txtEmail.setText("");
            txtCEP.setText("");
            txtEndereco.setText("");
            txtTelefone.setText("");


        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            e.printStackTrace();
        }
         

    }//GEN-LAST:event_btnOkActionPerformed

