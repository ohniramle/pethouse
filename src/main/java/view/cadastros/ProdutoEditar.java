    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        
        ProdutoDAO dao = new ProdutoDAO();
        Produto produto = new Produto();
        if (Id == null) { //se o ID do produto for nulo
                
                 JOptionPane.showMessageDialog(this, "Produto não existe!"); 
     
            } else {
                 // Usa o ID que foi passado
                produto.setId_produto(Id);
                dao.atualizar(produto);    // Atualiza no banco 
                JOptionPane.showMessageDialog(this, "Produto editado com sucesso!");
                 txtNome.setText("");
                 txtDescricao.setText("");
                 txtPreco.setText("");
                
            }   
      
           
    }//GEN-LAST:event_btnEditarActionPerformed
   //Método que recebe Servico Bean e preenche os campos de texto quando o usuário quer editar algum serviço existente
    public void preencherCampos (Produto p){
            if(p!=null){
                txtNome.setText(p.getNome());
                txtDescricao.setText(p.getDescricao());
                txtPreco.setText(Double.toString(p.getPreco()));
                
            }
    }
    
